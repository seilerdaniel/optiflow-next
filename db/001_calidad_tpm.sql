-- Module 4 · Quality (QMS) and preventive maintenance (TPM).
--
-- Both features were declared in the legacy `supabase_schema.sql` but never
-- applied to this database: the old server created them at boot from
-- `ensureSchema()`. The Next.js app has no boot hook, so the schema lives here
-- and is applied explicitly with `npm run db:esquema`.
--
-- Every statement is idempotent: running this file twice must be a no-op.

begin;

-- ---------------------------------------------------------------------------
-- TPM · one row per machine. Hours are NET worked hours of the SECTOR, so a
-- machine never needs a counter of its own: `horas_ultimo_mantenimiento` is a
-- snapshot of that accumulator taken when the service was registered.
-- ---------------------------------------------------------------------------
create table if not exists public.maquinas_tpm (
  id                         bigint generated by default as identity primary key,
  sector_id                  bigint not null references public.sectores(id) on delete cascade,
  nombre_maquina             text   not null,
  tarea_mantenimiento        text   not null,
  intervalo_horas_target     double precision not null default 100,
  horas_ultimo_mantenimiento double precision not null default 0,
  activo                     smallint not null default 1,
  fecha_creacion             text   not null,
  fecha_actualizacion        text   not null
);

-- Same machine name cannot repeat inside one sector, case-insensitive.
create unique index if not exists uq_tpm_sector_maquina
  on public.maquinas_tpm (sector_id, lower(nombre_maquina));

create index if not exists idx_tpm_sector on public.maquinas_tpm (sector_id);

create table if not exists public.historial_mantenimiento (
  id                          bigint generated by default as identity primary key,
  maquina_tpm_id              bigint not null references public.maquinas_tpm(id) on delete cascade,
  tecnico_operario            text   not null,
  fecha_hora                  text   not null,
  horas_acumuladas_al_service double precision not null default 0,
  observaciones               text,
  fecha_creacion              text   not null
);

create index if not exists idx_hist_tpm_maquina
  on public.historial_mantenimiento (maquina_tpm_id, fecha_hora);

-- ---------------------------------------------------------------------------
-- QMS · non-conformities. The table already exists in the plant database, but
-- it is declared here too so a fresh environment is complete after one run.
-- ---------------------------------------------------------------------------
create table if not exists public.no_conformidades (
  id                   bigint generated by default as identity primary key,
  ot_id                bigint not null references public.ordenes_trabajo(id) on delete cascade,
  sector_id            bigint not null references public.sectores(id),
  operario_responsable text,
  encargado_reporta    text not null,
  tipo_falla           text not null check (tipo_falla in (
    'Rotura de placa / Astillado',
    'Error de veta',
    'Defecto de laca / Lustre',
    'Falla de mecanizado / Cota',
    'Error de plano',
    'Otro'
  )),
  observacion          text,
  foto_url             text,
  estado               text not null default 'Pendiente' check (estado in (
    'Pendiente', 'En Reproceso', 'Resuelto', 'Descartado'
  )),
  accion_correctiva    text,
  resuelto_por         text,
  fecha_resolucion     timestamptz,
  fecha_registro       timestamptz not null default current_timestamp,
  fecha_actualizacion  timestamptz not null default current_timestamp
);

create index if not exists idx_nc_ot on public.no_conformidades (ot_id, fecha_registro desc);
create index if not exists idx_nc_sector on public.no_conformidades (sector_id, fecha_registro desc);
create index if not exists idx_nc_estado on public.no_conformidades (estado, fecha_registro desc);
create index if not exists idx_nc_fecha on public.no_conformidades (fecha_registro desc);

commit;
