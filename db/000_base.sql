-- Module 0 · Base schema: production floor, operators and access control.
--
-- These nine tables predate the Next.js migration: the legacy Express backend
-- created them at boot from `ensureSchema()`. Without them the app cannot even
-- log a user in, so they are the first file the runner applies.
--
-- Applied explicitly with `npm run db:esquema`. Every statement is idempotent:
-- running this file twice must be a no-op, and every object here mirrors the
-- live database (the legacy `supabase_schema.sql` was compared against a real
-- introspection before writing it).
--
-- No `begin`/`commit` here: `db/run-schema.js` wraps each file in its own
-- transaction. `001_calidad_tpm.sql` and `002_despiece.sql` own their modules
-- and must not be duplicated in this file.
--
-- Conventions carried over from the legacy backend, because the application
-- still depends on them:
--   * Dates are `text` ISO-8601 UTC ("2026-10-14T15:03:07.123Z"). The code
--     compares them with `substr(fecha, 1, 10)` and `new Date(iso)`, so
--     `timestamptz` would shift every comparison.
--   * Boolean flags are `smallint` 0/1, not `boolean`: the API and the client
--     read them as numbers.

-- ---------------------------------------------------------------------------
-- Work sectors (the plant's routing steps).
-- ---------------------------------------------------------------------------
create table if not exists public.sectores (
  id                  bigint generated by default as identity primary key,
  nombre_sector       text     not null,
  nombre_corto        text     not null,
  es_compartido       smallint not null default 0,
  clave_especial      text,
  linea_area          text     not null default 'General',
  orden_flujo         integer  not null default 0,
  operarios_sugeridos text,
  activo              smallint not null default 1,
  constraint sectores_nombre_sector_key unique (nombre_sector),
  constraint sectores_linea_area_chk
    check (linea_area in ('Placares', 'Cocinas', 'Compartido', 'General'))
);

create index if not exists idx_sectores_linea
  on public.sectores (linea_area, orden_flujo);

-- ---------------------------------------------------------------------------
-- Work orders (the unit everything else hangs from).
-- ---------------------------------------------------------------------------
create table if not exists public.ordenes_trabajo (
  id                  bigint generated by default as identity primary key,
  numero_ot           text     not null,
  cliente             text     not null,
  modelo              text,
  linea_area          text     not null default 'Placares',
  metros_lineales     double precision not null default 0,
  fecha_prometida     text,
  requiere_vidrio     smallint not null default 0,
  requiere_lustre     smallint not null default 0,
  requiere_herreria   smallint not null default 0,
  requiere_especiales smallint not null default 0,
  estado_general      text     not null default 'En Cola',
  fecha_creacion      text     not null,
  fecha_actualizacion text     not null,
  constraint ordenes_trabajo_numero_ot_key unique (numero_ot),
  constraint ordenes_linea_area_chk check (linea_area in ('Placares', 'Cocinas')),
  constraint ordenes_estado_chk
    check (estado_general in ('En Cola', 'En Producción', 'Detenido', 'Finalizado'))
);

create index if not exists idx_ord_estado on public.ordenes_trabajo (estado_general);
create index if not exists idx_ord_linea on public.ordenes_trabajo (linea_area);

-- ---------------------------------------------------------------------------
-- Operators. `nombre_norm` is the case-insensitive identity of a person: it is
-- derived on the server, never accepted from the client.
-- ---------------------------------------------------------------------------
create table if not exists public.operarios (
  id             bigint generated by default as identity primary key,
  nombre         text     not null,
  nombre_norm    text     not null,
  activo         smallint not null default 1,
  fecha_creacion text     not null,
  constraint operarios_nombre_norm_key unique (nombre_norm)
);

create index if not exists idx_op_activo on public.operarios (activo);

-- ---------------------------------------------------------------------------
-- Application users. Passwords are scrypt (N=16384, r=8, p=1) over a 16-byte
-- salt, both stored as hex; see `src/lib/auth.ts`.
--
-- RLS is enabled and NO policy is defined: only the owner role (the one in
-- `SUPABASE_DB_URL`) can read these rows. The browser never talks to Postgres
-- directly, it goes through the Next.js API.
-- ---------------------------------------------------------------------------
create table if not exists public.usuarios (
  id                  bigint generated by default as identity primary key,
  usuario             text     not null,
  nombre              text     not null,
  nombre_norm         text     not null,
  email               text,
  password_hash       text     not null,
  password_salt       text     not null,
  rol                 text     not null default 'operario',
  activo              smallint not null default 1,
  ultimo_acceso       text,
  fecha_creacion      text     not null,
  fecha_actualizacion text     not null,
  constraint usuarios_usuario_key unique (usuario),
  constraint usuarios_nombre_norm_key unique (nombre_norm),
  constraint usuarios_rol_chk check (rol in ('admin', 'encargado', 'operario'))
);

alter table public.usuarios enable row level security;

-- ---------------------------------------------------------------------------
-- Time records: one row per stage of a work order. Only two partial unique
-- indexes prevent nonsense that a plain constraint cannot express:
--   * one open stage per (order, sector);
--   * one open stage per operator, so nobody is clocked in twice at once.
-- ---------------------------------------------------------------------------
create table if not exists public.registros_tiempos (
  id                  bigint generated by default as identity primary key,
  ot_id               bigint not null references public.ordenes_trabajo (id) on delete cascade,
  sector_id           bigint not null references public.sectores (id),
  operario_nombre     text   not null,
  fecha_hora_inicio   text   not null,
  fecha_hora_fin      text,
  duracion_minutos    double precision,
  estado_etapa        text   not null default 'En Proceso',
  motivo_pausa        text,
  observacion         text,
  pausa_inicio        text,
  segundos_pausados   double precision not null default 0,
  fecha_creacion      text   not null,
  fecha_actualizacion text   not null,
  constraint registros_estado_chk
    check (estado_etapa in ('En Proceso', 'Pausado', 'Finalizado'))
);

create index if not exists idx_reg_ot_sector
  on public.registros_tiempos (ot_id, sector_id, estado_etapa);
create index if not exists idx_reg_estado on public.registros_tiempos (estado_etapa);
create index if not exists idx_reg_inicio on public.registros_tiempos (fecha_hora_inicio);
create index if not exists idx_reg_operario on public.registros_tiempos (operario_nombre);
create index if not exists idx_reg_fin on public.registros_tiempos (fecha_hora_fin);

create unique index if not exists uq_reg_ot_sector_abierta
  on public.registros_tiempos (ot_id, sector_id)
  where estado_etapa in ('En Proceso', 'Pausado');

create unique index if not exists uq_reg_operario_abierto
  on public.registros_tiempos (lower(operario_nombre))
  where estado_etapa in ('En Proceso', 'Pausado');

-- ---------------------------------------------------------------------------
-- Pause events. `registros_tiempos.segundos_pausados` is the running total;
-- these rows keep the detail (reason, observation, duration) of every pause.
-- ---------------------------------------------------------------------------
create table if not exists public.eventos_pausa (
  id             bigint generated by default as identity primary key,
  registro_id    bigint not null references public.registros_tiempos (id) on delete cascade,
  motivo_pausa   text   not null,
  observacion    text,
  inicio_pausa   text   not null,
  fin_pausa      text,
  segundos       double precision not null default 0,
  fecha_creacion text   not null
);

create index if not exists idx_pau_registro on public.eventos_pausa (registro_id, fin_pausa);
create index if not exists idx_pau_inicio on public.eventos_pausa (inicio_pausa);

-- ---------------------------------------------------------------------------
-- Material list of an order (plates required vs. plates consumed).
-- ---------------------------------------------------------------------------
create table if not exists public.ot_materiales (
  id                  bigint generated by default as identity primary key,
  ot_id               bigint not null references public.ordenes_trabajo (id) on delete cascade,
  material_nombre     text   not null,
  cantidad_placas     double precision not null check (cantidad_placas > 0),
  cantidad_consumida  double precision not null default 0
                        check (cantidad_consumida >= 0),
  observaciones       text,
  fecha_creacion      text   not null,
  fecha_actualizacion text   not null
);

create index if not exists idx_mat_ot on public.ot_materiales (ot_id);

-- ---------------------------------------------------------------------------
-- Sessions. Only the SHA-256 of the token is stored; a database leak cannot be
-- replayed as a login. Same RLS rule as `usuarios`: enabled, no policy.
-- ---------------------------------------------------------------------------
create table if not exists public.sesiones (
  id             bigint generated by default as identity primary key,
  usuario_id     bigint not null references public.usuarios (id) on delete cascade,
  token_hash     text   not null,
  ip             text,
  user_agent     text,
  creada_en      text   not null,
  expira_en      text   not null,
  cerrada_en     text,
  fecha_creacion text   not null,
  constraint sesiones_token_hash_key unique (token_hash)
);

create index if not exists idx_ses_usuario on public.sesiones (usuario_id, cerrada_en);
create index if not exists idx_ses_expira on public.sesiones (expira_en);
create index if not exists idx_ses_vencidas
  on public.sesiones (creada_en)
  where cerrada_en is null;

alter table public.sesiones enable row level security;

-- ---------------------------------------------------------------------------
-- Monthly production targets. One row per `YYYY-MM`; when a month has no row
-- the metrics code falls back to defaults instead of inserting from a Server
-- Component, so this table starts empty.
-- ---------------------------------------------------------------------------
create table if not exists public.objetivos_produccion (
  id                    bigint generated by default as identity primary key,
  periodo               varchar(7) not null,
  meta_metros_totales   numeric(10,2) not null default 1200.00,
  meta_metros_placares  numeric(10,2) not null default 800.00,
  meta_metros_cocinas   numeric(10,2) not null default 400.00,
  meta_unidades_totales numeric(12,2),
  meta_monto_total      numeric(14,2),
  categoria_o_area      varchar(40),
  creado_el             timestamptz not null default current_timestamp,
  constraint objetivos_produccion_periodo_key unique (periodo)
);

-- ---------------------------------------------------------------------------
-- Supabase-only hardening (no-op on a plain PostgreSQL).
--
-- The legacy project exposed `anon` and `authenticated` roles; the Next.js
-- backend connects with the owner role, so those roles must not keep any
-- privilege on the schema.
-- ---------------------------------------------------------------------------
do $seguridad$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on all tables in schema public from anon';
    execute 'revoke all on all sequences in schema public from anon';
    execute 'revoke execute on all functions in schema public from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on all tables in schema public from authenticated';
    execute 'revoke all on all sequences in schema public from authenticated';
    execute 'revoke execute on all functions in schema public from authenticated';
  end if;
end
$seguridad$;
